"""Source-level draft inventory; does not replace a LaTeX build or editorial review."""
import collections
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def clean(text):
    return re.sub(r"(?<!\\)%[^\n]*", "", text)


def read(path):
    return clean(path.read_text(encoding="utf-8"))


def expand(path):
    text = read(path)
    return re.sub(r"\\input\{([^}]+)\}",
                  lambda m: expand(ROOT / (m[1] if m[1].endswith(".tex") else m[1] + ".tex")), text)


def main():
    main_text = read(ROOT / "main.tex")
    chapters = re.findall(r"\\chapterfile\{(\d+)\}\{([^}]+)\}", main_text)
    texts = {f"chapters/{number}-{key}.tex": expand(ROOT / f"chapters/{number}-{key}.tex")
             for number, key in chapters}
    labels = collections.Counter("ch:" + key for _, key in chapters)
    for text in texts.values():
        labels.update(re.findall(r"\\label\{([^}]+)\}", text))
    bib = "\n".join(p.read_text(encoding="utf-8") for p in (ROOT / "bib").glob("*.bib"))
    keys = set(re.findall(r"@\w+\s*\{\s*([^,\s]+)\s*,", bib))
    lines = ["# Manuscript source audit", "",
             "Generated by `scripts/audit_manuscript.py`. Counts are approximate source words,",
             "including captions and equations, excluding line comments. Introduction includes its input files.",
             "References in generated blurbs, macros, conditionals, and verbatim text require a LaTeX build",
             "for definitive verification. This is an inventory, not an editorial-readiness certificate.", "",
             "| Chapter | File | Approximate words |", "|---|---|---:|"]
    missing_refs, missing_cites = [], []
    for index, (path, text) in enumerate(texts.items(), 1):
        words = len(re.findall(r"\b[\w'-]+\b", re.sub(r"\\[a-zA-Z]+", "", text)))
        lines.append(f"| {index} | {path} | {words:,} |")
        for match in re.finditer(r"\\(?:ref|eqref|pageref|autoref)\{([^}]*)\}", text):
            if match[1] not in labels:
                missing_refs.append(f"- `{path}`: `{match[0]}`")
        for match in re.finditer(r"\\cite\w*\*?(?:\[[^]]*\])*\{([^}]*)\}", text):
            for key in match[1].split(","):
                if key.strip() not in keys:
                    missing_cites.append(f"- `{path}`: `{key.strip()}`")
    for title, entries in [("Unresolved source references", missing_refs),
                           ("Citation keys absent from bibliography", missing_cites),
                           ("Repeated labels (including chapterfile labels)",
                            [f"- `{key}`: {count}" for key, count in labels.items() if count > 1])]:
        lines += ["", "## " + title, ""] + (sorted(set(entries)) or ["None found by this scan."])
    out = ROOT / "editorial" / "source-audit.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
